"""Model → ordered, commented YAML for ``crates/<id>.yml`` and ``keys/<id>.yml``.

Ordering rule (AGENTS.md): most important first (Name, Item, Rewards, Costs),
advanced/deep options last, mirroring the in-game editor where relevant.  Every
key written here is traced in ``docs/schema.md`` — never add a key the plugin
does not read.

``generate_*`` re-parses its own output and refuses to return it on any
mismatch (round-trip validation, AGENTS.md principle 6).
"""

from __future__ import annotations

from typing import Optional

from . import yamlkit as y
from .model import (
    CrateConfig,
    KeyConfig,
    CostOption,
    Limits,
    Milestone,
    ParticleSpec,
    PluginDefaults,
    Reward,
)
from .snbt import ItemSpec, write_item_provider

__all__ = [
    "generate_crate",
    "generate_key",
    "build_crate_tree",
    "build_key_tree",
    "capitalize_underscored",
]


def capitalize_underscored(value: str) -> str:
    """nightcore ``StringUtil.capitalizeUnderscored`` (cost/reward name default)."""
    words = value.replace("_", " ").split()
    return " ".join(word[:1].upper() + word[1:].lower() for word in words)


# ------------------------------------------------------------------- item helper


def _item(spec: ItemSpec, comment: Optional[list[str]] = None) -> y.Node:
    return y.from_plain(write_item_provider(spec), comment=comment)


# ------------------------------------------------------------------------ crate


def build_crate_tree(c: CrateConfig) -> y.Mapping:
    root = y.Mapping()
    root.comment = [
        "ExcellentCrates crate configuration.",
        "Generated by ExcellentCrates Config Studio — comments are ignored by",
        "Bukkit's YAML reader and can be kept or removed freely.",
        "Drop this file into plugins/ExcellentCrates/crates/ and the matching",
        "key file into plugins/ExcellentCrates/keys/.",
    ]

    root.set(
        "_dataver",
        y.Scalar(
            PluginDefaults.DATAVER,
            comment=[
                "Data version marker. Must be present: without it the plugin",
                "rewrites this file and drops a backup into backups/.",
            ],
        ),
    )

    # ---- required: identity -------------------------------------------------
    root.set(
        "Name",
        y.Scalar(
            c.name,
            comment=[
                "Display name ('&' color codes allowed, never '§').",
                "Shown in menus, holograms and chat broadcasts.",
            ],
        ),
    )
    root.set(
        "Description",
        y.from_plain(
            list(c.description),
            comment=["Lore lines shown under the name (holograms / menus)."],
        ),
    )

    # ---- required: item -----------------------------------------------------
    root.set(
        "ItemProvider",
        _item(
            c.item,
            comment=[
                "The crate's inventory item.",
                f"Current: {c.item.provider} / {c.item.display_material()} x{c.item.amount}.",
            ],
        ),
    )
    root.set(
        "ItemStackable",
        y.Scalar(
            c.item_stackable,
            comment=["Allow stacking multiple crates in one inventory slot."],
        ),
    )

    # ---- required: rewards --------------------------------------------------
    rewards = y.Mapping(
        comment=[
            "Rewards rolled when the crate is opened.",
            "A crate needs at least one reward. Weight is relative within a",
            "rarity; rarities must exist in config.yml (Rewards.Rarities).",
        ]
    )
    for reward in c.rewards:
        rewards.set(reward.id, _reward(reward))
    root.set("Rewards", y.Mapping([("List", rewards)]))

    # ---- costs (crate → key link) ------------------------------------------
    if c.costs:
        costs = y.Mapping(
            comment=[
                "Cost options: what the player pays for one opening.",
                "A key cost links this crate to a key file (Keys/<id>.yml).",
                "Leave empty for a free crate.",
            ]
        )
        for cost in c.costs:
            costs.set(cost.id, _cost(cost))
        root.set("CostOptions", costs)

    # ---- permissions / menus -----------------------------------------------
    root.set(
        "Permission_Required",
        y.Scalar(
            c.permission_required,
            comment=[
                "true = players need the 'excellentcrates.crate.<crate id>'",
                "permission to open this crate.",
            ],
        ),
    )
    root.set(
        "Preview",
        y.Mapping(
            [
                ("Enabled", y.Scalar(c.preview_enabled)),
                (
                    "Id",
                    y.Scalar(
                        c.preview_id,
                        comment=[
                            "Preview menu id. 'default' always exists;",
                            "other ids must exist in the plugin's menus folder.",
                        ],
                    ),
                ),
            ],
            comment=["Preview menu (players browse rewards before opening)."],
        ),
    )
    root.set(
        "Animation",
        y.Mapping(
            [
                ("Enabled", y.Scalar(c.animation_enabled)),
                (
                    "Id",
                    y.Scalar(
                        c.animation_id,
                        comment=[
                            "Opening animation provider. Fresh server ids:",
                            ", ".join(PluginDefaults.OPENING_IDS) + ".",
                            "'default' is NOT valid and reports a problem.",
                        ],
                    ),
                ),
            ],
            comment=[
                "Opening animation (rolling GUI). Enabled=false opens instantly",
                "with no animation (valid, no problems).",
            ],
        ),
    )
    root.set(
        "OpeningCooldown",
        y.Mapping(
            [
                ("Enabled", y.Scalar(c.cooldown_enabled)),
                (
                    "Value",
                    y.Scalar(
                        c.cooldown_value,
                        comment=["0 = off, -1 = once per player, >0 = seconds."],
                    ),
                ),
            ],
            comment=["Cooldown between openings."],
        ),
    )
    root.set(
        "OpeningLimits",
        y.Mapping(
            [
                (
                    "Amount",
                    y.Scalar(
                        c.opening_limit_amount,
                        comment=["Minimum 1 = unlimited unless a plugin limits it."],
                    ),
                )
            ],
            comment=["Max openings (per player)."],
        ),
    )

    # ---- linked world blocks ------------------------------------------------
    block = y.Mapping(
        comment=[
            "Blocks in the world that act as this crate.",
            "Use the link tool in-game to get 'x,y,z,world' positions.",
        ]
    )
    block.set(
        "Positions",
        y.from_plain(
            list(c.positions),
            comment=["Format: x,y,z,world — e.g. 14,2,1,world. Empty = not placed."],
        ),
    )
    block.set(
        "Pushback",
        y.Mapping(
            [("Enabled", y.Scalar(c.pushback_enabled))],
            comment=["Knock players back when they open the crate."],
        ),
    )
    block.set(
        "Hologram",
        y.Mapping(
            [
                ("Enabled", y.Scalar(c.hologram_enabled)),
                (
                    "Template",
                    y.Scalar(
                        c.hologram_template,
                        comment=["Hologram template id; 'default' always exists."],
                    ),
                ),
                (
                    "Y_Offset",
                    y.Scalar(
                        c.hologram_y_offset,
                        comment=["Vertical offset above the block."],
                    ),
                ),
            ],
            comment=["Floating name/description above the crate."],
        ),
    )
    effect = y.Mapping(
        comment=["Spinning effect around the linked blocks."]
    )
    effect.set("Enabled", y.Scalar(c.effect_enabled))
    effect.set(
        "Model",
        y.Scalar(
            c.effect_model,
            comment=["Effect model: " + ", ".join(PluginDefaults.EFFECT_MODELS) + "."],
        ),
    )
    effect.set("Particle", _particle(c.particle))
    block.set("Effect", effect)
    root.set("Block", block)

    # ---- post-open commands -------------------------------------------------
    root.set(
        "Post-Open",
        y.Mapping(
            [
                (
                    "Commands",
                    y.from_plain(
                        list(c.post_open_commands),
                        comment=[
                            "Run by the console after every opening.",
                            "No leading '/', first word must be a server command.",
                        ],
                    ),
                )
            ],
            comment=["Commands executed after each open."],
        ),
    )

    # ---- milestones ---------------------------------------------------------
    if c.milestones:
        milestones = y.Mapping(
            comment=[
                "Reward after N total openings (global config.yml must have",
                "Milestones.Enabled: true). List keys are 0,1,2...",
            ]
        )
        milestones.set("Repeatable", y.Scalar(c.milestones_repeatable))
        entries = y.Mapping()
        for i, milestone in enumerate(c.milestones):
            entries.set(
                str(i),
                y.Mapping(
                    [
                        (
                            "Reward_Id",
                            y.Scalar(
                                milestone.reward_id,
                                comment=["Must match a reward id under Rewards.List."],
                            ),
                        ),
                        (
                            "Openings",
                            y.Scalar(
                                milestone.openings,
                                comment=["Openings required to unlock it."],
                            ),
                        ),
                    ]
                ),
            )
        milestones.set("List", entries)
        root.set("Milestones", milestones)

    _emit_extra(root, c.extra)

    return root


def _emit_extra(root: y.Mapping, extra: dict) -> None:
    for key, node in extra.items():
        comment = getattr(node, "comment", None)
        if comment is None and hasattr(node, "comment"):
            node.comment = ["Unknown key preserved from the imported file."]
        root.set(key, node)


def _reward(reward: Reward) -> y.Mapping:
    node = y.Mapping(
        comment=[
            f"Type {reward.type} · rarity {reward.rarity} · weight {reward.weight:g}.",
        ]
    )
    node.set("Type", y.Scalar(reward.type, comment=["ITEM or COMMAND."]))
    node.set(
        "Rarity",
        y.Scalar(
            reward.rarity,
            comment=[
                "Rarity id from config.yml (default: common, rare, mythic).",
                "Unknown ids fall back to the most common rarity (logged error).",
            ],
        ),
    )
    node.set(
        "Weight",
        y.Scalar(
            float(reward.weight),
            comment=["Relative weight inside its rarity. Must be > 0."],
        ),
    )

    if reward.type == "COMMAND":
        node.set("Name", y.Scalar(reward.name or capitalize_underscored(reward.id)))
        node.set("Description", y.from_plain(list(reward.description)))
        node.set(
            "Commands",
            y.from_plain(
                list(reward.commands),
                comment=["Console commands, no leading '/'. At least one required."],
            ),
        )
    else:
        items = y.Mapping(
            comment=[
                "Giveable items (random pick). Keys are 0,1,2... — at least one",
                "required, shown in roll order as fallback display.",
            ]
        )
        for i, spec in enumerate(reward.items):
            items.set(str(i), _item(spec))
        node.set("ItemsData", items)

    node.set("PreviewData", _item(_reward_preview(reward)))

    if reward.type == "ITEM":
        node.set(
            "Custom_Preview",
            y.Scalar(
                reward.custom_preview,
                comment=["true = show PreviewData instead of the first item."],
            ),
        )
        node.set(
            "Placeholder_Apply",
            y.Scalar(
                reward.placeholder_apply,
                comment=["Allow placeholders in item name/lore."],
            ),
        )

    node.set(
        "Broadcast",
        y.Scalar(reward.broadcast, comment=["Announce the win to the server."]),
    )
    node.set(
        "Required_Permissions",
        y.from_plain(
            list(reward.required_permissions),
            comment=["Player must have ALL of these permissions to win."],
        ),
    )
    node.set(
        "Ignored_For_Permissions",
        y.from_plain(
            list(reward.ignored_permissions),
            comment=["Permissions that skip this reward's restrictions."],
        ),
    )
    node.set("Limits", _limits(reward.limits))
    return node


def _reward_preview(reward: Reward) -> ItemSpec:
    if reward.preview is not None:
        return reward.preview
    if reward.type == "ITEM" and reward.items:
        return reward.items[0]
    return ItemSpec(material="PAPER", name=reward.name)


def _limits(limits: Limits) -> y.Mapping:
    node = y.Mapping(
        comment=[
            "Win limits / cooldown for this reward.",
            "-1 = unlimited, 0 = no cooldown, CooldownType: DAILY (reset at",
            "midnight) or CUSTOM (seconds).",
        ]
    )
    node.set("Enabled", y.Scalar(limits.enabled))
    node.set("CooldownType", y.Scalar(limits.cooldown_type))
    node.set("GlobalAmount", y.Scalar(int(limits.global_amount)))
    node.set("PlayerAmount", y.Scalar(int(limits.player_amount)))
    node.set("GlobalCooldown", y.Scalar(int(limits.global_cooldown)))
    node.set("PlayerCooldown", y.Scalar(int(limits.player_cooldown)))
    return node


def _cost(cost: CostOption) -> y.Mapping:
    node = y.Mapping(
        comment=[f"Entries: {len(cost.entries)} (each entry is one thing to pay)."]
    )
    node.set("Enabled", y.Scalar(cost.enabled))
    node.set(
        "Name",
        y.Scalar(
            cost.name or capitalize_underscored(cost.id),
            comment=["Shown in the cost menu."],
        ),
    )
    node.set("Icon", _item(cost.icon))
    entries = y.Mapping(comment=["Entry keys are 0,1,2... — at least one required."])
    for i, entry in enumerate(cost.entries):
        entry_node = y.Mapping()
        entry_node.set("Type", y.Scalar(entry.type, comment=["'key' or 'currency'."]))
        if entry.type == "key":
            entry_node.set(
                "Key",
                y.Scalar(
                    entry.key_id,
                    comment=["Key id = file name of keys/<id>.yml (crate link)."],
                ),
            )
            entry_node.set("Amount", y.Scalar(int(entry.amount)))
        else:
            entry_node.set(
                "Currency",
                y.Scalar(entry.currency, comment=["Currency id of your economy plugin."]),
            )
            entry_node.set("Amount", y.Scalar(float(entry.amount)))
        entries.set(str(i), entry_node)
    node.set("Entries", entries)
    return node


def _particle(p: ParticleSpec) -> y.Mapping:
    node = y.Mapping(
        comment=[
            "Particle used by the effect. Unknown names silently fall back to",
            "CLOUD. VIBRATION / DUST_COLOR_TRANSITION / TRAIL are unsupported.",
        ]
    )
    node.set("Name", y.Scalar(p.name, comment=["Bukkit Particle enum name."]))
    if p.material:
        node.set("Material", y.Scalar(p.material, comment=["For BLOCK/DUST_PILLAR style particles."]))
    if p.color:
        node.set("Color", y.Scalar(p.color, comment=["Red,Green,Blue — e.g. 255,128,0."]))
    if p.name in ("DUST", "DUST_COLOR_TRANSITION", "BLOCK_CRUMBLE"):
        node.set("Size", y.Scalar(float(p.size)))
    if p.power != 1.0:
        node.set("Power", y.Scalar(float(p.power)))
    return node


# ------------------------------------------------------------------------- key


def build_key_tree(k: KeyConfig) -> y.Mapping:
    root = y.Mapping()
    root.comment = [
        "ExcellentCrates key configuration.",
        "Generated by ExcellentCrates Config Studio.",
        "Drop this file into plugins/ExcellentCrates/keys/.",
    ]
    root.set(
        "Name",
        y.Scalar(k.name, comment=["Display name ('&' color codes allowed)."]),
    )
    root.set(
        "Virtual",
        y.Scalar(
            k.virtual,
            comment=[
                "true = no physical item, pure counter in player data.",
                "false = players hold the item below.",
            ],
        ),
    )
    root.set("ItemData", _item(k.item, comment=["The key item players hold."]))
    root.set(
        "ItemStackable",
        y.Scalar(k.item_stackable, comment=["Allow stacking keys in one slot."]),
    )
    _emit_extra(root, k.extra)
    return root


# ------------------------------------------------------------------ generation


def _generate(tree: y.Mapping, kind: str) -> str:
    text = y.emit(tree)
    try:
        parsed = y.parse(text)
    except y.YamlError as exc:  # pragma: no cover — emitter bug
        raise RuntimeError(f"round-trip parse failed for {kind}: {exc}") from exc
    if not y.values_equal(tree, parsed):
        raise RuntimeError(f"round-trip mismatch for {kind} — refusing to write")
    return text


def generate_crate(c: CrateConfig) -> str:
    return _generate(build_crate_tree(c), f"crate '{c.id}'")


def generate_key(k: KeyConfig) -> str:
    return _generate(build_key_tree(k), f"key '{k.id}'")
